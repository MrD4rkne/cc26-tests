def add0():
    return 7


def add1(a):
    return a + 7


def add2(a, b):
    return a + b + 7


def add3(a, b, c):
    return a + b + c + 7


def add4(a, b, c, d):
    return a + b + c + d + 7


def add5(a, b, c, d, e):
    return a + b + c + d + e + 7


def add6(a, b, c, d, e, f):
    return a + b + c + d + e + f + 7


a = 2
b = 3
c = 5
d = 7
e = 11
f = 13

print(add0())
print(add1(a))
print(add2(a, b))
print(add3(a, b, c))
print(add4(a, b, c, d))
print(add5(a, b, c, d, e))
print(add6(a, b, c, d, e, f))
